"""The core API: every operation that code outside msx/ uses on a machine
(machine-core "Host and frontend reach the core only through the core API").

`Machine` implements it structurally; a wrapper of a native core can
implement it later. The inspection queries return integers, bytes or flat
records of integers and bytes (msx/boundary.py), and change no emulated
state. No member takes a callback the core calls (machine-core "The core
API has no callback into the host"): a break is the step_frame stop reason
and the last-stop query. Two shapes change in later steps: the disk path,
and the exceptions that load_state and mount_disk raise
(allium/core-frontend.allium).
"""
from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Protocol, runtime_checkable

if TYPE_CHECKING:
    from msx.boundary import (
        CpuRegisters,
        DiskMedium,
        FrameOutput,
        MediaId,
        RgbFrame,
        StopInfo,
        VdpInfo,
    )
    from msx.input import InputFrame
    from msx.machine import Machine
    from msx.machine_spec import KeyboardLayout
    from msx.vdp._geometry import VideoStandard


@runtime_checkable
class CoreApi(Protocol):
    """The machine as code outside msx/ sees it."""

    # -- machine properties --------------------------------------------------

    @property
    def cycle_count(self) -> int: ...
    @property
    def video_standard(self) -> VideoStandard: ...
    @property
    def keyboard_layout(self) -> KeyboardLayout: ...
    def samples_per_frame(self) -> int: ...

    # -- running ---------------------------------------------------------------

    def step_frame(self, frame_input: InputFrame, render_video: bool) -> FrameOutput: ...
    def apply_input(self, frame_input: InputFrame) -> None: ...
    def step(self) -> int: ...
    def reset(self) -> None: ...

    # -- media -------------------------------------------------------------------

    def dirty_media(self) -> list[MediaId]: ...
    def read_media(self, media_id: MediaId) -> bytes: ...
    def mark_persisted(self, media_id: MediaId) -> None: ...
    def mount_disk(self, drive: int, medium: DiskMedium | None) -> bytes | None: ...
    def disk_mounted(self, drive: int) -> bool: ...
    def disk_path(self, drive: int) -> Path | None: ...

    # -- save states -------------------------------------------------------------

    def save_state(self) -> bytes: ...
    def load_state(self, data: bytes, source: str = "<state>") -> None: ...

    # -- attachments -----------------------------------------------------------

    def attach_mouse(self, port: int) -> None: ...

    # -- break settings ------------------------------------------------------------

    def set_breakpoints(self, addrs: list[int]) -> None: ...
    def set_watchpoints(self, entries: list[tuple[int, int]]) -> None: ...
    def set_temp_breakpoint(self, addr: int | None) -> None: ...
    def set_step_out(self, sp: int) -> None: ...
    def set_frame_breakpoint(self, frame: int | None) -> None: ...
    def set_break_halt_di(self, enabled: bool) -> None: ...
    def set_sp_range(self, rng: tuple[int, int] | None) -> None: ...

    # -- break control ---------------------------------------------------------------

    def request_break(self) -> None: ...
    def last_stop(self) -> StopInfo: ...

    # -- inspection queries --------------------------------------------------------

    def cpu_registers(self) -> CpuRegisters: ...
    def read_memory(self, addr: int, length: int) -> bytes: ...
    def write_memory(self, addr: int, data: bytes) -> None: ...
    def vram_size(self) -> int: ...
    def read_vram(self, addr: int, length: int) -> bytes: ...
    def vdp_info(self) -> VdpInfo: ...
    def frame_number(self) -> int: ...
    def drive_count(self) -> int: ...
    def main_ram_range(self) -> tuple[int, int]: ...
    def breakpoints(self) -> tuple[int, ...]: ...
    def watchpoints(self) -> tuple[tuple[int, int], ...]: ...
    def break_halt_di(self) -> bool: ...
    def render_preview(self) -> RgbFrame: ...


if TYPE_CHECKING:
    # mypy fails here when Machine stops matching the core API.
    _MACHINE_IS_CORE_API: type[CoreApi] = Machine
